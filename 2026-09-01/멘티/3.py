# ----------------------------------------
# 문제 6. z-점수로 CPU온도 이상 찾기
# ----------------------------------------
# CPU온도 열 전체의 평균과 표준편차(ddof=0)를 소수 둘째 자리로 한 줄에 출력하세요.
# 이어서 z-점수 절댓값이 3을 넘는 개수와 2를 넘는 개수를 한 줄에 출력하세요.
# 힌트: 표준편차 메서드에는 n으로 나눌지 n-1로 나눌지 정하는 인자가 있습니다.
#       조건을 만족하는 개수는 True/False 시리즈의 합으로 셀 수 있습니다.
# 기대 출력: 68.38 7.86
#            0 0

# CPU온도 전체 평균, 표준편차 출력
print(df["CPU온도"].mean().round(2), df["CPU온도"].std(ddof=0).round(2))

# z-점수 개수 출력
z = (df["CPU온도"] - df["CPU온도"].mean()) / df["CPU온도"].std(ddof=0)
print((z.abs() > 3).sum(), (z.abs() > 2).sum())


# ----------------------------------------
# 문제 7. IQR로 메모리 이상 찾기
# ----------------------------------------
# 메모리 열 전체의 아래·위 울타리(임계값 1.5)를 소수 둘째 자리로 한 줄에 출력하고,
# 울타리를 벗어난 개수를 출력하세요.
# 이어서 걸린 행이 어느 구역에서 나왔는지 개수를 출력하세요.
# 힌트: 원하는 분위수(25%, 75%)를 구해 주는 메서드가 있습니다. 조건에 맞는 행만
#       골라내려면 대괄호 안에 조건식을 넣으면 됩니다. 두 조건을 잇는 기호는 | 입니다.
# 기대 출력: 1.08 59.76
#            3
#            {'Z3-찰리': 3}

# 메모리 열 울타리 값 출력
q1, q3 = np.percentile(df["메모리"], 25), np.percentile(df["메모리"], 75)
iqr = q3 - q1
low, high = q1 - 1.5 * iqr, q3 + 1.5 * iqr
print(low.round(2), high.round(2))

# 마스크 생성
mask = (df["메모리"] < low) | (df["메모리"] > high)

# 울타리 벗어난 개수 출력
print(len(df["메모리"][mask]))

# 걸린 행 어느 구역, 개수?
memory_err = df.loc[mask, "구역"].value_counts().to_dict()
print(memory_err)

