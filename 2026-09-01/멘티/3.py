# ----------------------------------------
# 문제 9. 0~1로 스케일 맞추고 파일로 남기기
# ----------------------------------------
# 지표 4열을 표 전체의 최솟값·최댓값을 기준으로 Min-Max 정규화하세요.
# 열별 최솟값, 최댓값, 평균을 소수 셋째 자리로 차례로 출력하세요.
# 이어서 수집시각·구역 두 열 뒤에 정규화한 지표 4열(소수 넷째 자리)을 붙여
# 정규화_멘티.csv 로 저장하고, 다시 읽어 표 크기를 출력하세요.
# 이 파일도 멘토에게 함께 넘깁니다.
# 힌트: 열별 최솟값·최댓값 메서드를 쓰면 (표 - 최솟값) / (최댓값 - 최솟값) 계산이
#       열끼리 알아서 맞춰져 한 번에 됩니다. CSV 저장 메서드에는 인덱스를 뺄지,
#       어떤 인코딩으로 쓸지 정하는 옵션이 있습니다. 표 두 개를 옆으로 이어 붙이는
#       함수도 판다스에 있습니다.
# 기대 출력: {'CPU온도': 0.0, '전력': 0.0, '응답시간': 0.0, '메모리': 0.0}
#            {'CPU온도': 1.0, '전력': 1.0, '응답시간': 1.0, '메모리': 1.0}
#            {'CPU온도': 0.515, '전력': 0.493, '응답시간': 0.49, '메모리': 0.414}
#            (179, 6)

# 지표 4열 가져오기
cols = ["CPU온도", "전력", "응답시간", "메모리"]

# df 복사본 생성
df_copy = df_remove7.copy()

# 각 열의 {min, max} 출력
cols_minmax = {
    c: {"min": float(df_remove7[c].min()), "max": float(df_remove7[c].max())}
    for c in cols
}

# 열별 최솟값, 최댓값, 평균 출력
for c in cols:
    lo = cols_minmax[c]["min"]
    hi = cols_minmax[c]["max"]
    df_copy[c] = (df_copy[c] - lo) / (hi - lo)

# 열별 최솟값, 최댓값, 평균 출력
min_values = df_copy[cols].min().round(3).to_dict()
max_values = df_copy[cols].max().round(3).to_dict()
mean_values = df_copy[cols].mean().round(3).to_dict()
print(min_values)
print(max_values)
print(mean_values)

# 정규화 열 추가
new_df = df_copy[["수집시각", "구역"] + cols].round(4)

# 정규화 열 추가 저장
new_df.to_csv("정규화_멘티.csv", index=False, encoding="utf-8-sig")

