# 지표 4열 남은 결측 총 개수
tot_null_counts = df[["CPU온도", "전력", "응답시간", "메모리"]].isna().sum().sum()
print(tot_null_counts)

# 채우는 데 쓴 값
print(np.round(df["CPU온도"].mean(), 2), np.round(df["메모리"].median(), 2))


# ----------------------------------------
# 문제 5. 구역별 요약
# ----------------------------------------
# 구역별 지표 4종 평균(소수 둘째 자리)을 표로 출력하고,
# 구역별 수집 건수를 구역 이름 순으로 출력하세요.
# 힌트: 표를 어떤 열의 값별로 묶은 뒤 묶음마다 집계해 주는 메서드가 있습니다.
#       반올림은 표 전체에 한 번에 적용할 수 있습니다.
