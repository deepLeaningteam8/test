# ----------------------------------------
# 문제 3. 중복 행 제거
# ----------------------------------------
# 완전히 같은 행이 몇 개인지 출력하고, 지운 뒤 표 크기를 출력하세요.
# 인덱스는 0부터 다시 매깁니다.
# 힌트: 각 행이 중복인지 True/False로 알려 주는 메서드와 중복 행을 지워 주는
#       메서드는 서로 다릅니다. 인덱스를 0부터 다시 매기는 메서드도 따로 있습니다.
# 기대 출력: 4
#            (182, 8)

# 중복 행 개수
print(df.duplicated().sum())

# 중복 행 지우기
df = df.drop_duplicates()

