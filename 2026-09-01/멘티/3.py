print(df.shape)

# ----------------------------------------
# 문제 4. 결측 채우기
# ----------------------------------------
# CPU온도는 CPU온도 열 전체 평균으로, 메모리는 메모리 열 전체 중앙값으로,
# 전력은 전력 열 전체 평균으로 채우세요.
# 채운 뒤 지표 4열의 남은 결측 총 개수를 출력하고,
# 채우는 데 쓴 CPU온도 평균과 메모리 중앙값을 소수 둘째 자리로 한 줄에 출력하세요.
# 힌트: 결측을 원하는 값으로 채워 주는 메서드가 있습니다. 평균·중앙값을 구하는
#       메서드는 결측을 알아서 빼고 계산하니 먼저 구해 두고 채우면 됩니다.
# 기대 출력: 0
#            68.38 29.78

# 대치
df["CPU온도"] = df["CPU온도"].fillna(df["CPU온도"].mean())
df["메모리"] = df["메모리"].fillna(df["메모리"].median())
