print(df["전력"].head().dtype)

# 상태 열 값별 개수
alarm_dict = df["상태"].value_counts().to_dict()
print(alarm_dict)

# ----------------------------------------
# 문제 2. 숫자로 저장되지 않은 열 고치기
# ----------------------------------------
# 전력 열을 숫자로 바꾸세요. 숫자로 못 바꾸는 값은 결측으로 만듭니다.
# 바꾼 뒤 전력 열의 결측 개수와 평균(소수 둘째 자리)을 출력하세요.
# 힌트: 판다스에는 열을 통째로 숫자로 바꿔 주는 함수가 있고, 바꾸다 실패한 값을
