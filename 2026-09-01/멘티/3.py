# 상태 열의 값별 개수를 차례로 출력하세요. 한글이 깨지지 않게 읽습니다.
# 힌트: 표의 크기를 담고 있는 속성, 열마다 결측 개수를 세어 주는 메서드,
#       한 열의 값별 개수를 세어 주는 메서드가 판다스에 있습니다. 찾아보세요.
#       값 하나의 자료형 이름을 문자열로 얻는 방법은 파이썬 내장 기능에 있습니다.
